//! TypeScript binding export, and the guards that keep it honest.
//!
//! Architecture §2.5 and decision D7. The export runs inside `cargo test`, CI
//! then runs `git diff --exit-code` over the emitted directory, and
//! `pnpm verify:drift-guard` proves that gate can still fail.
//!
//! **The export path is a compile-time constant** ([`GENERATED_FILE`]), not an
//! environment variable. This is the direct lesson of nightcore issue #422,
//! where `TS_RS_EXPORT_DIR` came from a `.cargo/config.toml` that cargo resolves
//! by walking up from the *current directory* rather than from `--manifest-path`.
//! A run from the repo root left it unset, the generator wrote to a gitignored
//! default, and `git diff` over the guarded directory was clean because nothing
//! had been written there — so the drift guard passed vacuously for the entire
//! life of the project. `env!("CARGO_MANIFEST_DIR")` is baked in at compile time
//! and cannot vary with the caller's cwd.
//!
//! That constant is a *build-machine* path, which is exactly what §2.3 forbids
//! at **runtime** ("never `CARGO_MANIFEST_DIR` as a runtime path — it is a build
//! machine path; a CI-built release shipped broken over exactly this"). Nothing
//! here runs in the shipped app: [`export`] is called by a test and by the drift
//! guard, both of which run from a checkout where that path is correct by
//! construction.

