/// The file the type bindings are emitted to, resolved at compile time.
pub const GENERATED_FILE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../packages/contracts/src/generated/core.ts"
);

/// Banner prepended to the emitted file.
const HEADER: &str = "\
// Generated by `cargo test -p shiranami-core` (specta). DO NOT EDIT.
//
// Regenerate with:  cargo test -p shiranami-core --lib bindings
// CI diffs this file and fails on drift; `pnpm verify:drift-guard` proves that
// gate is not vacuous. See docs/v2/architecture.md §2.5.
";

